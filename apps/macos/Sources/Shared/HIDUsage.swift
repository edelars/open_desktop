import Foundation

// Table `kVK_*` (NSEvent.keyCode) -> USB HID usage of the Keyboard/Keypad page 0x07 (INPUT_TRANSPORT_V1.md 6.2, task S10-16).
//
// Sources and editions:
//   - USB-IF HID Usage Tables for USB, version 1.7 ("HUT 1.7"), chapter 10 Keyboard/Keypad Page (0x07), chapter 12 Button Page (0x09).
//     The usage IDs below are the HUT 1.7 numbers. The table was written from them and from the examples of section 6.2 of the
//     protocol; it was NOT re-checked against the PDF line by line (the PDF was not available to the author of this file).
//   - macOS SDK 27.0 (Xcode 27, `xcrun --show-sdk-version` = 27.0), HIToolbox/Events.h: the set of `kVK_*` constants. The unit test
//     reads that header from the installed SDK and requires every constant to be in `keyboard` or in `untransmittable`.
// Key codes are positional: ANSI, ISO and JIS layouts are translated by the guest (section 6.2).
//
// Left/right modifiers: the code of `flagsChanged` says which key changed; the device-dependent bit of `modifierFlags`
// (IOKit NX_DEVICE*KEYMASK) says whether it went down or up (section 6.3).

public enum HIDUsage {
    public static let capsLockKeyCode: UInt16 = 0x39

    /// `kVK_*` -> usage ID (page 0x07).
    public static let keyboard: [UInt16: UInt16] = [
        // ANSI letters (kVK_ANSI_A ... kVK_ANSI_Z), HUT 0x04...0x1D
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, 0x05: 0x0A, 0x04: 0x0B, 0x22: 0x0C,
        0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, 0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13, 0x0C: 0x14, 0x0F: 0x15,
        0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B, 0x10: 0x1C, 0x06: 0x1D,
        // ANSI digits 1...9, 0: HUT 0x1E...0x27
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22, 0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25, 0x19: 0x26, 0x1D: 0x27,
        // Return, Escape, Delete (Backspace), Tab, Space
        0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,
        // Minus, Equal, [ ], backslash, ; ' grave , . /
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31, 0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38,
        // ISO Section -> Keyboard Non-US \ and |
        0x0A: 0x64,
        // Caps Lock
        0x39: 0x39,
        // F1...F12: HUT 0x3A...0x45
        0x7A: 0x3A, 0x78: 0x3B, 0x63: 0x3C, 0x76: 0x3D, 0x60: 0x3E, 0x61: 0x3F, 0x62: 0x40, 0x64: 0x41, 0x65: 0x42, 0x6D: 0x43, 0x67: 0x44, 0x6F: 0x45,
        // F13...F20: HUT 0x68...0x6F
        0x69: 0x68, 0x6B: 0x69, 0x71: 0x6A, 0x6A: 0x6B, 0x40: 0x6C, 0x4F: 0x6D, 0x50: 0x6E, 0x5A: 0x6F,
        // Help (the key in the Insert position), Home, Page Up, Forward Delete, End, Page Down
        0x72: 0x49, 0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x77: 0x4D, 0x79: 0x4E,
        // Arrows: Right, Left, Down, Up
        0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52,
        // Context menu -> Application
        0x6E: 0x65,
        // Keypad: Clear (Num Lock position), / * - + Enter, 1...9, 0, ., =
        0x47: 0x53, 0x4B: 0x54, 0x43: 0x55, 0x4E: 0x56, 0x45: 0x57, 0x4C: 0x58,
        0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B, 0x56: 0x5C, 0x57: 0x5D, 0x58: 0x5E, 0x59: 0x5F, 0x5B: 0x60, 0x5C: 0x61,
        0x52: 0x62, 0x41: 0x63, 0x51: 0x67,
        // JIS: Keypad Comma, Yen (International3), Underscore/Ro (International1), Eisu (LANG2), Kana (LANG1)
        0x5F: 0x85, 0x5D: 0x89, 0x5E: 0x87, 0x66: 0x91, 0x68: 0x90,
        // Modifiers: left Control, Shift, Option, Command -> 0xE0...0xE3; right -> 0xE4...0xE7
        0x3B: 0xE0, 0x38: 0xE1, 0x3A: 0xE2, 0x37: 0xE3, 0x3E: 0xE4, 0x3C: 0xE5, 0x3D: 0xE6, 0x36: 0xE7,
    ]

    /// `kVK_*` constants that are not transmitted, with the reason (section 6.2: "записан как непередаваемый").
    static let untransmittable: [UInt16: String] = [
        0x3F: "kVK_Function (Fn): no usage on the Keyboard/Keypad page (section 6.2)",
        0x48: "kVK_VolumeUp: Consumer page media key, out of v1 (section 13)",
        0x49: "kVK_VolumeDown: Consumer page media key, out of v1 (section 13)",
        0x4A: "kVK_Mute: Consumer page media key, out of v1 (section 13)",
    ]

    public static func usage(forKeyCode code: UInt16) -> UInt16? { keyboard[code] }

    /// Device-dependent bit of `NSEvent.modifierFlags.rawValue` for a modifier key code (IOKit NX_DEVICE*KEYMASK):
    /// left Control 0x1, left Shift 0x2, right Shift 0x4, left Command 0x8, right Command 0x10, left Option 0x20,
    /// right Option 0x40, right Control 0x2000. nil for every other code.
    public static func deviceModifierMask(forKeyCode code: UInt16) -> UInt? {
        switch code {
        case 0x3B: return 0x0001
        case 0x38: return 0x0002
        case 0x3C: return 0x0004
        case 0x37: return 0x0008
        case 0x36: return 0x0010
        case 0x3A: return 0x0020
        case 0x3D: return 0x0040
        case 0x3E: return 0x2000
        default: return nil
        }
    }

    /// `NSEvent.buttonNumber` -> Button Page usage (section 5.2); nil for n >= 5 (not transmitted, counted by the caller).
    public static func buttonUsage(forButtonNumber number: Int) -> UInt16? {
        (0...4).contains(number) ? UInt16(number + 1) : nil
    }
}
