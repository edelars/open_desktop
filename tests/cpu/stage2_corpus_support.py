"""Shared strict file, JSON and digest operations for Stage 2 CPU corpora."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any


class CorpusError(ValueError):
    """A generated corpus bundle or its manifest is invalid."""


def sha256(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def strict_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise CorpusError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def verify_file_set(directory: Path, expected: dict[str, bytes]) -> None:
    entries = list(directory.iterdir())
    if any(entry.is_symlink() or not entry.is_file() for entry in entries):
        raise CorpusError("corpus directory may contain only regular files")
    if {entry.name for entry in entries} != set(expected):
        raise CorpusError("corpus files are missing or unexpected files are present")
    for name, wanted in expected.items():
        if (directory / name).read_bytes() != wanted:
            raise CorpusError(f"generated bytes or manifest digest differ for {name}")


def write_file_set(directory: Path, expected: dict[str, bytes]) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    current = list(directory.iterdir())
    if any(entry.is_symlink() or not entry.is_file() for entry in current):
        raise CorpusError("refusing to write into a corpus directory containing non-files or symlinks")
    if {entry.name for entry in current} - set(expected):
        raise CorpusError("refusing to overwrite a directory containing unrelated files")
    for name, contents in expected.items():
        (directory / name).write_bytes(contents)
    verify_file_set(directory, expected)
